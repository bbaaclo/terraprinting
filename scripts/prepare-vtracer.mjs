// The official @visioncortex/vtracer package is built for Node.js: its last
// few lines load the .wasm file with `fs`. Everything else is plain
// wasm-bindgen glue that also works in a browser. This script copies the glue
// into src/vendor/vtracer/ as an ES module and swaps only the Node loader for
// a browser one. It runs automatically after `npm install`.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@visioncortex/vtracer/package.json'));
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src', 'vendor', 'vtracer');
mkdirSync(outDir, { recursive: true });

let glue = readFileSync(join(pkgDir, 'pkg', 'vtracer_wasm.js'), 'utf8');

const nodeLoader = /const wasmPath = `\$\{__dirname\}\/vtracer_wasm_bg\.wasm`;\s*const wasmBytes = require\('fs'\)\.readFileSync\(wasmPath\);\s*const wasmModule = new WebAssembly\.Module\(wasmBytes\);\s*let wasmInstance = new WebAssembly\.Instance\(wasmModule, __wbg_get_imports\(\)\);\s*let wasm = wasmInstance\.exports;\s*wasm\.__wbindgen_start\(\);\s*$/;
if (!nodeLoader.test(glue)) {
  throw new Error('prepare-vtracer: the vtracer package layout changed. Check pkg/vtracer_wasm.js before upgrading.');
}
glue = glue.replace(nodeLoader, `let wasm;
export async function initVtracer(wasmBytes) {
  if (wasm) return;
  const { instance } = await WebAssembly.instantiate(wasmBytes, __wbg_get_imports());
  wasm = instance.exports;
  wasm.__wbindgen_start();
}
`);
glue = glue.replace(/^exports\.(\w+) = \1;$/gm, 'export { $1 };');
if (/require\(|__dirname|exports\./.test(glue)) {
  throw new Error('prepare-vtracer: Node-only code left in the glue.');
}

writeFileSync(join(outDir, 'vtracer.js'), '// Generated by scripts/prepare-vtracer.mjs. Do not edit.\n' + glue);
copyFileSync(join(pkgDir, 'pkg', 'vtracer_wasm_bg.wasm'), join(outDir, 'vtracer_bg.wasm'));
console.log('prepare-vtracer: browser build written to src/vendor/vtracer/');
